-- 1. Create warehouses
show warehouses;
create or replace warehouse management_wh;


-- 2. Network policies and PAT token
USE ROLE SECURITYADMIN;

CREATE NETWORK POLICY stug_demo_net_policy
  ALLOWED_IP_LIST = ('0.0.0.0/0')
  COMMENT = 'Temporary permissive policy for STUG Perth DCM demo';
  
USE ROLE ACCOUNTADMIN;

ALTER USER JAMES_PROD SET NETWORK_POLICY = stug_demo_net_policy;

ALTER USER JAMES_PROD
  ADD PROGRAMMATIC ACCESS TOKEN stug_dcm_pat
  DAYS_TO_EXPIRY = 30;


-- 3. Create a DCM role
USE ROLE USERADMIN;
CREATE ROLE DCM_DEPLOYER;


--4. Grant specific infrastructure permissions
USE ROLE SYSADMIN;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE DCM_DEPLOYER;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE DCM_DEPLOYER;


-- 5. Grant specific security power (via SECURITYADMIN)
USE ROLE SECURITYADMIN;
GRANT MANAGE GRANTS ON ACCOUNT TO ROLE DCM_DEPLOYER;


-- 6. Give access to account admin
USE ROLE ACCOUNTADMIN;
GRANT ROLE DCM_DEPLOYER TO ROLE ACCOUNTADMIN;


-- 7. Create the database and schema for the project
USE ROLE SYSADMIN;
CREATE DATABASE MANAGEMENT_DB;
CREATE SCHEMA MANAGEMENT_DB.DCM;


-- 8. Grant to privilege to create DCM projects.
GRANT CREATE DCM PROJECT ON SCHEMA MANAGEMENT_DB.DCM TO ROLE DCM_DEPLOYER;


-- 9 . Grant the privilege to create roles
USE ROLE SECURITYADMIN;
GRANT CREATE ROLE ON ACCOUNT TO ROLE DCM_DEPLOYER;


USE ROLE ACCOUNTADMIN;
-- 10. Ensure the rle has usage on the database and specific schema
GRANT USAGE ON DATABASE MANAGEMENT_DB TO ROLE DCM_DEPLOYER;
GRANT USAGE ON SCHEMA MANAGEMENT_DB.DCM TO ROLE DCM_DEPLOYER;


-- 11. The CLI needs permission to create a temporary stage
GRANT CREATE STAGE ON SCHEMA MANAGEMENT_DB.DCM TO ROLE DCM_DEPLOYER;


-- 12 Give it full operational access to stages in this schema
GRANT USAGE, READ, WRITE ON ALL STAGES IN SCHEMA MANAGEMENT_DB.DCM TO ROLE DCM_DEPLOYER;
GRANT USAGE, READ, WRITE ON FUTURE STAGES IN SCHEMA MANAGEMENT_DB.DCM TO ROLE DCM_DEPLOYER;


-- 13. Other Grants
GRANT MANAGE GRANTS ON ACCOUNT TO ROLE DCM_DEPLOYER;

USE ROLE DCM_DEPLOYER;
CREATE OR REPLACE DCM PROJECT MANAGEMENT_DB.DCM.DCM_PROD;

-- GIVE THE DCM_DEPLOYER USAGE ON THE MANAGEMENT WAREHOUSE
GRANT USAGE ON WAREHOUSE MANAGEMENT_WH TO ROLE DCM_DEPLOYER;